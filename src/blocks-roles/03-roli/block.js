function init(root) {
  var R = DATA.roles;
  root.innerHTML = '<h2 class="dbv-h2">' + esc(DATA.title) + '</h2>' +
    tbl(DATA.head, R.map(function (r) { return ['<b>' + esc(r.t) + '</b>', esc(r.who), r.q ? list(r.q.map(esc)) : esc(r.p)]; }), { first: 'th', gl: 1, cap: DATA.title, cls: ['dbv-w1', 'dbv-w2', ''] });
  var trs = root.querySelectorAll('tbody tr');
  R.forEach(function (r, i) { trs[i].id = 'dbv-role-' + r.key; });
  dbvGlossary(root).apply(root);
  var timer = 0;
  function flash(key) {
    var tr = document.getElementById('dbv-role-' + key);
    if (!tr || !root.contains(tr)) return;
    tr.scrollIntoView({ behavior: reduced() ? 'auto' : 'smooth', block: 'center' });
    clearTimeout(timer);
    [].forEach.call(root.querySelectorAll('.is-flash'), function (x) { x.classList.remove('is-flash'); });
    tr.classList.add('is-flash');
    timer = setTimeout(function () { tr.classList.remove('is-flash'); }, 2000);
  }
  document.addEventListener('dbv:openrole', function (e) { if (e.detail && e.detail.key) flash(e.detail.key); });
  function fromHash() { var m = /^#dbv-role-([a-z]+)$/.exec(location.hash || ''); if (m) flash(m[1]); }
  window.addEventListener('hashchange', fromHash);
  fromHash();
}
function start() {
  [].forEach.call(document.querySelectorAll('.dbv-rl'), function (r) {
    if (r.getAttribute('data-dbv-init')) return;
    r.setAttribute('data-dbv-init', '1');
    init(r);
  });
}
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
