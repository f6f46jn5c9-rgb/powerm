function init(root) {
  var tot = DATA.steps.reduce(function (a, s) { return a + s.m; }, 0);
  var slides = tbl(DATA.sHead, DATA.slides.map(function (s, i) { return [String(i + 1), '<b>' + esc(s[0]) + '</b>', esc(s[1]) + ' ' + esc(s[2])]; }), { gl: 1, cap: DATA.sH, cls: ['dbv-n dbv-w1', 'dbv-w2', ''] });
  var people = tbl(DATA.pHead, DATA.people.map(function (p) {
    var sc = typeof p[3] === 'string' ? esc(p[3]) : p[3].scale.map(function (s) { return '<span class="dbv-zn"><span class="dbv-dot" style="background:' + s[1] + '" aria-hidden="true"></span>' + esc(s[0]) + '</span>'; }).join('') + ' <span class="dbv-small">' + esc(p[3].note) + '</span>';
    return ['<b>' + esc(p[0]) + '</b>', esc(p[1]), esc(p[2]), sc];
  }), { gl: 1, cap: DATA.pH, cls: ['dbv-wa', 'dbv-wb', 'dbv-wc', ''] });
  var jury = DATA.jury.map(function (j) {
    var d = j.p ? '<p>' + esc(j.p) + '</p>' : '';
    if (j.items) d += '<p>' + esc(j.items.join(' ')) + '</p><p><b>' + esc(j.strong) + '</b></p>';
    if (j.p2) d = '<p>' + esc(j.p + ' ' + j.p2) + '</p>';
    return '<div class="dbv-dl__r"><dt>' + esc(j.k) + '</dt><dd data-gl>' + d + '</dd></div>';
  }).join('');
  root.innerHTML =
    '<section class="dbv-sec dbv-stack"><h2 class="dbv-h2">' + esc(DATA.title) + '</h2><p class="dbv-body" data-gl>' + esc(DATA.lead) + '</p>' +
    '<div role="img" aria-label="' + esc(DATA.tlLabel) + '"><div class="dbv-tm" aria-hidden="true">' + DATA.steps.map(function (s) { return '<i style="width:' + (100 * s.m / tot) + '%;background:' + s.c + '"></i>'; }).join('') + '</div>' +
    '<ul class="dbv-tml" aria-hidden="true">' + DATA.steps.map(function (s) { return '<li><span class="dbv-sw" style="background:' + s.c + '"></span>' + esc(s.t) + '</li>'; }).join('') + '</ul></div>' +
    '<h3 class="dbv-h3 dbv-sub">' + esc(DATA.sH) + '</h3>' + slides +
    '<h3 class="dbv-h3 dbv-sub">' + esc(DATA.jH) + '</h3><dl class="dbv-dl">' + jury + '</dl></section>' +
    '<section class="dbv-sec dbv-stack"><h2 class="dbv-h2">' + esc(DATA.pH) + '</h2>' + people + '</section>' +
    '<section class="dbv-sec dbv-stack"><h2 class="dbv-h2">' + esc(DATA.kH) + '</h2><div class="dbv-note" role="note" data-gl>' +
    DATA.items.map(function (it) { return '<p><b>' + esc(it[0]) + '</b> ' + esc(it[1]) + '</p>'; }).join('') + '</div></section>';
  dbvGlossary(root).apply(root);
}
[].forEach.call(document.querySelectorAll('.dbv-def'), function (r) {
  if (r.getAttribute('data-dbv-init')) return;
  r.setAttribute('data-dbv-init', '1');
  init(r);
});
