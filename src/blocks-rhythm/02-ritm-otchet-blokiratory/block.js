function init(root) {
  var D = DATA.demo, Rp = DATA.report, B = DATA.blocker;
  var meet = tbl(DATA.head, DATA.rows.map(function (r) {
    var what = r.link ? '<a href="#' + r.link + '" data-jump="' + r.link + '">' + esc(r.what) + '</a>' : esc(r.what);
    return [esc(r.when), what, esc(r.org), r.who === '—' ? '<span class="dbv-no">—</span>' : esc(r.who)];
  }), { gl: 1, cap: DATA.title, cls: ['dbv-w1', '', 'dbv-w3', 'dbv-w4'] });
  var pairs = tbl(Rp.head, Rp.pairs.map(function (p) { return [esc(p[0]), esc(p[1])]; }), { cap: Rp.h, cls: ['dbv-wh', ''] });
  root.innerHTML =
    '<section class="dbv-sec dbv-stack"><h2 class="dbv-h2">' + esc(DATA.title) + '</h2>' + meet + '</section>' +
    '<section class="dbv-sec dbv-stack" id="dbv-demo"><h3 class="dbv-h3">' + esc(D.h) + '</h3>' +
    '<div class="dbv-key" role="note"><p><b>' + esc(D.key) + '</b></p></div>' +
    '<div class="dbv-stack" data-gl>' + D.paras.map(function (p) { return '<p class="dbv-body"><b>' + esc(p[0]) + '</b> ' + esc(p[1]) + '</p>'; }).join('') + '</div></section>' +
    '<section class="dbv-sec dbv-stack" id="dbv-report"><h3 class="dbv-h3">' + esc(Rp.h) + '</h3><p class="dbv-body" data-gl>' + esc(Rp.lead) + '</p>' + pairs + '</section>' +
    '<section class="dbv-sec dbv-stack" id="dbv-blockers"><h3 class="dbv-h3">' + esc(B.h) + '</h3><div class="dbv-stack" data-gl><p class="dbv-body">' + esc(B.def) + '</p>' +
    flow(B.chain) + list(B.rules.map(esc)) +
    '<div class="dbv-warn" role="note"><p>' + esc(B.warn) + '</p></div></div></section>';
  dbvGlossary(root).apply(root);
  root.addEventListener('click', function (e) {
    var a = e.target.closest && e.target.closest('[data-jump]');
    if (a) { e.preventDefault(); scrollToId(a.getAttribute('data-jump')); }
  });
}
[].forEach.call(document.querySelectorAll('.dbv-rit'), function (r) {
  if (r.getAttribute('data-dbv-init')) return;
  r.setAttribute('data-dbv-init', '1');
  init(r);
});
